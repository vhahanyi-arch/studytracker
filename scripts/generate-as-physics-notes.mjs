// Copies the AS Physics revision notes from docs/as-physics-notes/ into a
// module the app can import. The markdown stays the single source of truth;
// this only moves it somewhere a Next.js build can reach.
//
//   pnpm notes:as
//
// tests/notes/sync.test.ts fails if the generated module and the markdown
// disagree, so an edit to the notes that is not regenerated cannot ship.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const NOTES_DIR = join(ROOT, "docs", "as-physics-notes");
export const OUTPUT = join(ROOT, "lib", "as-physics-notes.generated.ts");

/** topic-10-dc-circuits.md -> as-u10, matching asPhysicsUnits in portal-content. */
export function notesByUnit(dir = NOTES_DIR) {
  const notes = {};
  for (const file of readdirSync(dir)) {
    const topic = file.match(/^topic-(\d+)-.*\.md$/);
    if (!topic) continue;
    // Normalise line endings so a Windows checkout and CI generate the same file.
    notes[`as-u${Number(topic[1])}`] = readFileSync(join(dir, file), "utf8").replace(/\r\n?/g, "\n");
  }
  return Object.fromEntries(Object.entries(notes).sort(([a], [b]) => Number(a.slice(4)) - Number(b.slice(4))));
}

export function renderModule(notes = notesByUnit()) {
  const entries = Object.entries(notes).map(([id, markdown]) => `  ${JSON.stringify(id)}: ${JSON.stringify(markdown)},`);
  return [
    "// Generated by scripts/generate-as-physics-notes.mjs from docs/as-physics-notes/.",
    "// Do not edit by hand: change the markdown and run `pnpm notes:as`.",
    "// tests/notes/sync.test.ts fails if this file and the notes disagree.",
    "",
    "export const asPhysicsNotes: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const notes = notesByUnit();
  writeFileSync(OUTPUT, renderModule(notes));
  console.log(`wrote ${Object.keys(notes).length} topics to lib/as-physics-notes.generated.ts`);
}
