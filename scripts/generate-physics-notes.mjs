// Copies the physics revision notes from docs/ into modules the app can
// import: docs/as-physics-notes/ into lib/as-physics-notes.generated.ts and
// docs/igcse-physics-notes/ into lib/igcse-physics-notes.generated.ts. The
// markdown stays the single source of truth; this only moves it somewhere a
// Next.js build can reach. Each level is its own module, so a student only
// downloads the notes for the course they open.
//
//   pnpm notes
//
// tests/notes/content.test.ts fails if a generated module and its markdown
// disagree, so an edit to the notes that is not regenerated cannot ship.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Each level's notes folder under docs/, its module under lib/, and the unit
 * ids in portal-content its files map to.
 */
export const LEVELS = {
  // topic-10-dc-circuits.md -> as-u10, matching asPhysicsUnits.
  as: { folder: "as-physics-notes", file: /^topic-(\d+)-.*\.md$/, prefix: "as-u", module: "as-physics-notes.generated.ts", name: "asPhysicsNotes" },
  // unit-18-electromagnetic-effects.md -> igcse-u18, matching igcsePhysicsUnits.
  igcse: { folder: "igcse-physics-notes", file: /^unit-(\d+)-.*\.md$/, prefix: "igcse-u", module: "igcse-physics-notes.generated.ts", name: "igcsePhysicsNotes" },
};

export const notesDir = (level) => join(ROOT, "docs", LEVELS[level].folder);
export const outputFile = (level) => join(ROOT, "lib", LEVELS[level].module);

export function notesByUnit(level, dir = notesDir(level)) {
  const { file, prefix } = LEVELS[level];
  const notes = {};
  for (const name of readdirSync(dir)) {
    const unit = name.match(file);
    if (!unit) continue;
    // Normalise line endings so a Windows checkout and CI generate the same file.
    notes[`${prefix}${Number(unit[1])}`] = readFileSync(join(dir, name), "utf8").replace(/\r\n?/g, "\n");
  }
  const order = (id) => Number(id.slice(prefix.length));
  return Object.fromEntries(Object.entries(notes).sort(([a], [b]) => order(a) - order(b)));
}

export function renderModule(level, notes = notesByUnit(level)) {
  const { folder, name } = LEVELS[level];
  const entries = Object.entries(notes).map(([id, markdown]) => `  ${JSON.stringify(id)}: ${JSON.stringify(markdown)},`);
  return [
    `// Generated by scripts/generate-physics-notes.mjs from docs/${folder}/.`,
    "// Do not edit by hand: change the markdown and run `pnpm notes`.",
    "// tests/notes/content.test.ts fails if this file and the notes disagree.",
    "",
    `export const ${name}: Record<string, string> = {`,
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const level of Object.keys(LEVELS)) {
    const notes = notesByUnit(level);
    writeFileSync(outputFile(level), renderModule(level, notes));
    console.log(`wrote ${Object.keys(notes).length} ${level} units to lib/${LEVELS[level].module}`);
  }
}
